
clear;
clc;
close all;

%% PARAMETRI
a = 4.775e-2;           % Lato lungo [m]
c = 299792458;          % Velocita' della luce [m/s]

fc = c/(2*a);           % Cutoff TE10

fprintf('Cutoff TE10: %.4f GHz\n',fc/1e9);

%% FREQUENZA
f = linspace(fc,3*fc,2000);

%% CALCOLO BETA Z
k0 = 2*pi*f/c;
kc = pi/a;

beta_z = sqrt(k0.^2-kc^2);

%% CONFIGURAZIONE GRAFICA
fig = figure( ...
    'Color',[1 1 1], ...
    'InvertHardcopy','on', ...
    'Position',[100 100 1100 650], ...
    'Renderer','painters', ...
    'MenuBar','figure', ...
    'ToolBar','figure');

ax = axes(fig);

set(ax, ...
    'Color',[1 1 1], ...
    'XColor',[0 0 0], ...
    'YColor',[0 0 0], ...
    'FontName','DejaVu Sans', ...
    'FontSize',15, ...
    'LineWidth',1.1, ...
    'TickDir','out', ...
    'TickLength',[0.008 0.008], ...
    'Box','on', ...
    'Layer','top', ...
    'XMinorTick','on', ...
    'YMinorTick','on');

hold(ax,'on');

%% CURVA TEORICA
plot(ax,f/1e9,beta_z, ...
    'Color',[0.00 0.30 0.75], ...
    'LineWidth',2.5);

%% CUTOFF
xline(ax,fc/1e9,'--', ...
    sprintf('f_c = %.3f GHz',fc/1e9), ...
    'Color',[0.85 0.15 0.15], ...
    'LineWidth',1.6, ...
    'FontSize',13, ...
    'LabelVerticalAlignment','middle');

%% GRIGLIA
grid(ax,'on');
ax.GridColor = [0.75 0.75 0.75];
ax.GridAlpha = 0.45;

ax.MinorGridColor = [0.85 0.85 0.85];
ax.MinorGridAlpha = 0.35;

%% ETICHETTE
xlabel(ax,'Frequenza [GHz]', ...
    'FontSize',17, ...
    'FontWeight','bold', ...
    'Color','k');

ylabel(ax,'\beta_z [rad/m]', ...
    'FontSize',17, ...
    'FontWeight','bold', ...
    'Color','k');

title(ax,'Costante di propagazione teorica - TE_{10}', ...
    'FontSize',18, ...
    'FontWeight','bold', ...
    'Color','k');

%% LIMITI
xlim(ax,[fc/1e9 3*fc/1e9]);
ylim(ax,[0 1.08*max(beta_z)]);

%% LEGENDA
lgd = legend(ax,'\beta_z teorica', ...
    'Location','northwest');

set(lgd, ...
    'Color','w', ...
    'TextColor','k', ...
    'EdgeColor',[0.7 0.7 0.7], ...
    'FontSize',13);

%% SFONDO E RENDERING
set(fig,'InvertHardcopy','on');

